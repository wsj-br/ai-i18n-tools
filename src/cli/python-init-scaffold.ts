/**
 * Zero-dependency Python >=3.10 `i18n.py` scaffold.
 * Python 3.14 template strings are detected by type name so the file still parses on 3.10.
 */
export const PYTHON_I18N_MARKER = "ai-i18n-tools-i18n-py: 1";

export interface PythonI18nScaffoldOptions {
  sourceLocale: string;
  flatDir: string;
  gettextDir: string;
  domain: string;
  useFlat: boolean;
  useGettext: boolean;
}

const HELPER = String.raw`# Generated by ai-i18n-tools. Do not edit by hand.
# ai-i18n-tools-i18n-py: 1
"""Lookup-before-format translations for flat JSON and GNU Gettext.

Safe: t("Hello, {name}!", name=name), translate(t"Hello, {name}!") on Python 3.14,
and _("Hello, %s!") % name. Do not call _(f"..."), _("..." % value), or _("...".format(...));
Python evaluates those before any catalog lookup.

Reset ContextVar tokens in a finally block:

    token = set_locale(code)
    try:
        ...
    finally:
        reset_locale(token)
"""

from __future__ import annotations

import contextvars
import gettext as _gettext
import hashlib
import json
import re
import string
from pathlib import Path
from typing import Any, Mapping

_SOURCE_LOCALE = __SOURCE_LOCALE__
_FLAT_DIR = __FLAT_DIR__
_GETTEXT_DIR = __GETTEXT_DIR__
_DOMAIN = __DOMAIN__
_USE_FLAT = __USE_FLAT__
_USE_GETTEXT = __USE_GETTEXT__

_locale: contextvars.ContextVar[str] = contextvars.ContextVar(
    "ai_i18n_locale", default=_SOURCE_LOCALE
)
_backend: contextvars.ContextVar[str] = contextvars.ContextVar("ai_i18n_backend", default="auto")
_json_cache: dict[str, dict[str, str]] = {}
_mo_cache: dict[str, _gettext.NullTranslations] = {}
_FORMATTER = string.Formatter()


class _SafeFormatter(string.Formatter):
    def get_field(self, field_name: str, args: tuple[Any, ...], kwargs: Mapping[str, Any]):
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*|\d+", field_name):
            raise ValueError(field_name)
        return super().get_field(field_name, args, kwargs)


_SAFE = _SafeFormatter()
_ROOT = Path(__file__).resolve().parent


def set_locale(locale: str) -> contextvars.Token[str]:
    return _locale.set(locale.replace("_", "-"))


def reset_locale(token: contextvars.Token[str]) -> None:
    _locale.reset(token)


def get_locale() -> str:
    return _locale.get()


def set_backend(backend: str) -> None:
    if backend not in {"auto", "json", "gettext"}:
        raise ValueError(backend)
    _backend.set(backend)


def get_ui_languages() -> list[dict[str, Any]]:
    path = _manifest_path()
    if not path.is_file():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    return data if isinstance(data, list) else []


def get_direction(locale: str | None = None) -> str:
    code = locale or get_locale()
    for row in get_ui_languages():
        if row.get("code") == code:
            return "rtl" if row.get("direction") == "rtl" else "ltr"
    return "ltr"


def _(message: str) -> str:
    return _lookup(str(message))


def t(template: Any, /, *, plurals: bool = False, count: int | None = None, zero_digit: bool = False, **values: Any) -> str:
    del zero_digit
    if _is_template(template):
        source, extracted = _template_parts(template)
        merged = dict(extracted)
        merged.update(values)
        return t(source, plurals=plurals, count=count, **merged)
    text = str(template)
    if plurals:
        text = _lookup_plural(str(template), 0 if count is None else count)
    else:
        text = _lookup(str(template))
    data = dict(values)
    if count is not None:
        data.setdefault("count", count)
    if not data:
        return text
    return _format(str(template), text, data)


translate = t


def ngettext(singular: str, plural: str, n: int, **values: Any) -> str:
    if _active_backend() == "gettext":
        text = _mo().ngettext(singular, plural, n)
    else:
        text = _lookup_plural(singular, n) if _plural_key(singular) else (singular if n == 1 else plural)
        if text == singular and n != 1:
            hashed = _lookup_plural(singular, n)
            text = hashed if hashed != singular else plural
    data = dict(values)
    data.setdefault("count", n)
    template = singular if _plural_form(get_locale(), n) == "one" else plural
    return _format(template, text, data)


def pgettext(context: str, message: str, **values: Any) -> str:
    if _active_backend() == "gettext":
        text = _mo().pgettext(context, message)
    else:
        catalog = _json_for(get_locale())
        text = catalog.get(context + "\x04" + message) or catalog.get(message) or message
    if not values:
        return text
    return _format(message, text, values)


def streamlit_language_selector(sidebar: bool = True, key: str = "lang_selector") -> str:
    import streamlit as st

    rows = get_ui_languages()
    codes = [str(row.get("code")) for row in rows if row.get("code")]
    if not codes:
        codes = [_SOURCE_LOCALE]
    labels = {str(row.get("code")): str(row.get("label") or row.get("code")) for row in rows}
    current = st.session_state.get("locale") or st.query_params.get("lang") or get_locale()
    if current not in codes:
        current = _SOURCE_LOCALE if _SOURCE_LOCALE in codes else codes[0]
    host = st.sidebar if sidebar else st
    choice = host.selectbox(
        "Language",
        options=codes,
        index=codes.index(current),
        format_func=lambda code: labels.get(code, code),
        key=key,
    )
    st.session_state.locale = choice
    st.query_params["lang"] = choice
    set_locale(choice)
    return choice


def _manifest_path() -> Path:
    base = _FLAT_DIR if _USE_FLAT else _GETTEXT_DIR
    return _ROOT / base / "ui-languages.json"


def _active_backend() -> str:
    choice = _backend.get()
    if choice in {"json", "gettext"}:
        return choice
    if _USE_FLAT and (_ROOT / _FLAT_DIR / f"{get_locale()}.json").is_file():
        return "json"
    if _USE_GETTEXT:
        return "gettext"
    return "json" if _USE_FLAT else "gettext"


def _json_for(locale: str) -> dict[str, str]:
    cached = _json_cache.get(locale)
    if cached is not None:
        return cached
    path = _ROOT / _FLAT_DIR / f"{locale}.json"
    data: dict[str, str] = {}
    if path.is_file():
        loaded = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(loaded, dict):
            data = {str(key): str(value) for key, value in loaded.items()}
    _json_cache[locale] = data
    return data


def _mo() -> _gettext.NullTranslations:
    locale = get_locale()
    cached = _mo_cache.get(locale)
    if cached is not None:
        return cached
    localedir = str(_ROOT / _GETTEXT_DIR)
    found: _gettext.NullTranslations | None = None
    for code in (locale, locale.replace("-", "_")):
        try:
            found = _gettext.translation(_DOMAIN, localedir=localedir, languages=[code])
            break
        except OSError:
            continue
    if found is None:
        found = _gettext.NullTranslations()
    _mo_cache[locale] = found
    return found


def _lookup(message: str) -> str:
    if _active_backend() == "gettext":
        return _mo().gettext(message)
    return _json_for(get_locale()).get(message, message)


def _md5_8(text: str) -> str:
    return hashlib.md5(text.encode("utf-8")).hexdigest()[:8]


def _plural_key(message: str) -> str:
    return _md5_8(message.strip())


def _lookup_plural(message: str, n: int) -> str:
    if _active_backend() == "gettext":
        return _mo().ngettext(message, message, n)
    catalog = _json_for(get_locale())
    digest = _plural_key(message)
    form = "zero" if n == 0 and f"{digest}_zero" in catalog else _plural_form(get_locale(), n)
    return catalog.get(f"{digest}_{form}") or catalog.get(f"{digest}_other") or message


def _plural_form(locale: str, n: int) -> str:
    tag = locale.replace("_", "-").lower()
    language = tag.split("-", 1)[0]
    if language in {"ja", "zh", "ko", "vi", "id", "th", "ms"}:
        return "other"
    if tag == "pt-br" or language == "fr":
        return "one" if n < 2 else "other"
    if language in {"ru", "uk", "be", "sr", "hr", "bs"}:
        if n % 10 == 1 and n % 100 != 11:
            return "one"
        if 2 <= n % 10 <= 4 and not 10 <= n % 100 <= 20:
            return "few"
        return "many"
    if language == "pl":
        if n == 1:
            return "one"
        if 2 <= n % 10 <= 4 and not 10 <= n % 100 <= 20:
            return "few"
        return "many"
    if language in {"cs", "sk"}:
        if n == 1:
            return "one"
        if 2 <= n <= 4:
            return "few"
        return "other"
    if language == "ar":
        if n == 0:
            return "zero"
        if n == 1:
            return "one"
        if n == 2:
            return "two"
        if 3 <= n % 100 <= 10:
            return "few"
        if 11 <= n % 100 <= 99:
            return "many"
        return "other"
    return "one" if n == 1 else "other"


def _is_template(value: object) -> bool:
    kind = type(value)
    return kind.__name__ == "Template" and hasattr(value, "strings") and hasattr(value, "interpolations")


def _template_parts(value: Any) -> tuple[str, dict[str, Any]]:
    strings = list(value.strings)
    interpolations = list(value.interpolations)
    parts: list[str] = []
    extracted: dict[str, Any] = {}
    generated = 0
    for index, literal in enumerate(strings):
        parts.append(str(literal))
        if index >= len(interpolations):
            continue
        item = interpolations[index]
        expr = str(getattr(item, "expression", "") or "")
        conversion = getattr(item, "conversion", None)
        spec = str(getattr(item, "format_spec", "") or "")
        simple = expr.isidentifier()
        if simple:
            name = expr
        else:
            generated += 1
            name = f"value_{generated}"
        extracted[name] = getattr(item, "value", None)
        conv = f"!{conversion}" if conversion else ""
        spec_text = f":{spec}" if spec else ""
        parts.append("{" + name + conv + spec_text + "}")
    return "".join(parts), extracted


def _field_names(template: str) -> set[str]:
    names: set[str] = set()
    for _literal, field, _spec, _conv in _FORMATTER.parse(template):
        if field is None:
            continue
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*|\d+", field):
            raise ValueError(field)
        names.add(field)
    return names


def _apply_mustache(template: str, values: Mapping[str, Any]) -> str:
    def replace(match: re.Match[str]) -> str:
        key = match.group(1).strip()
        if key not in values:
            return match.group(0)
        return str(values[key])

    return re.sub(r"\{\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}\}", replace, template)


def _format(source: str, translated: str, values: Mapping[str, Any]) -> str:
    if re.search(r"%(\([^)]+\))?[#0\- +]*(\d+|\*)?(\.(\d+|\*))?[diouxXeEfFgGcrsa]", translated):
        try:
            return translated % values
        except Exception:
            return translated
    try:
        source_fields = _field_names(source)
        translated_fields = _field_names(translated)
    except ValueError:
        source_fields = set()
        translated_fields = {"__unsafe__"}
    chosen = translated if translated_fields <= source_fields else source
    text = _apply_mustache(chosen, values)
    try:
        return _SAFE.format(text, **dict(values))
    except (ValueError, KeyError, IndexError):
        fallback = _apply_mustache(source, values)
        try:
            return _SAFE.format(fallback, **dict(values))
        except (ValueError, KeyError, IndexError):
            return fallback
`;

export function renderPythonI18nHelper(options: PythonI18nScaffoldOptions): string {
  return HELPER.replace("__SOURCE_LOCALE__", JSON.stringify(options.sourceLocale))
    .replace("__FLAT_DIR__", JSON.stringify(options.flatDir))
    .replace("__GETTEXT_DIR__", JSON.stringify(options.gettextDir))
    .replace("__DOMAIN__", JSON.stringify(options.domain))
    .replace("__USE_FLAT__", options.useFlat ? "True" : "False")
    .replace("__USE_GETTEXT__", options.useGettext ? "True" : "False");
}

export function pythonScaffoldOptionsForTemplate(
  template: "ui-python" | "ui-python-gettext" | "ui-python-flask"
): PythonI18nScaffoldOptions {
  if (template === "ui-python-flask") {
    return {
      sourceLocale: "en",
      flatDir: "translations",
      gettextDir: "translations",
      domain: "messages",
      useFlat: false,
      useGettext: true,
    };
  }
  if (template === "ui-python-gettext") {
    return {
      sourceLocale: "en",
      flatDir: "locales",
      gettextDir: "locales",
      domain: "messages",
      useFlat: true,
      useGettext: true,
    };
  }
  return {
    sourceLocale: "en",
    flatDir: "locales",
    gettextDir: "locales",
    domain: "messages",
    useFlat: true,
    useGettext: false,
  };
}
